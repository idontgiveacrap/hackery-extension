const fs = require("fs");
const path = require("path");

const rootDir = path.join(__dirname, "..", "..");
const engineDir = path.join(rootDir, "network", "engine");
const coreSource = fs.readFileSync(
  path.join(engineDir, "network-rule-engine-core.js"),
  "utf8"
);
const pageSource = fs.readFileSync(
  path.join(engineDir, "network-hook-page.source.js"),
  "utf8"
);

// The core module is authored as ESM for the background/UI bundles. For the
// MAIN-world content-script hook we inline it as plain function declarations
// (no export/import, no globalThis) directly inside installNetworkHook's body,
// where sibling function declarations are visible to each other via hoisting.
const factorySource = coreSource
  .replace(/^import .*$/gm, "")
  .replace(/export\s*\{[^}]*\}\s*;?\s*$/m, "")
  .replace(/^export\s+(function|const|let|class)\s+/gm, "$1 ")
  .trim();

// installNetworkHook/buildLogBridgeBootstrap are exported so network/background.js
// (an ES module) can import them. The export keyword lives outside the function
// bodies, so it has no effect on Function.prototype.toString() output when
// scripting.executeScript({ func: installNetworkHook }) serializes the function
// for MAIN-world injection — only the function's own source text is reinjected.
const finalOutput = `/* GENERATED by network/scripts/build-network-hook.js — do not edit directly */

export function installNetworkHook(rules, version, logToken, sharedStateBundle) {
${factorySource}
${pageSource}
}

export function buildLogBridgeBootstrap(logToken) {
  return \`(function(){var LOG_TOKEN=\${JSON.stringify(logToken)};window.addEventListener("message",function(event){if(event.source!==window)return;var data=event.data;if(!data||(data.source!=="hackery-lab-network-hook"&&data.source!=="complex-linker-network-hook")||data.token!==LOG_TOKEN)return;if(data.type==="log"){browser.runtime.sendMessage({type:"NETWORK_RULE_LOG",entry:data.entry}).catch(function(){});return;}if(data.type==="sharedState"){browser.runtime.sendMessage({type:"NETWORK_SHARED_STATE",persistent:data.persistent,tab:data.tab}).catch(function(){});}});})();\`;
}
`;

fs.writeFileSync(
  path.join(engineDir, "network-hook-install.js"),
  finalOutput
);
console.log("Wrote network/engine/network-hook-install.js");
